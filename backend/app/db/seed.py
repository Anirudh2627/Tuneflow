"""Database seeding from processed/sample data.

Loads ``data/sample/*.csv`` (generated by ``python scripts/download_data.py
--source sample``) or the processed parquet tables, and populates the
catalog plus a demo user with listening history so the frontend has
something to show immediately.
"""
from __future__ import annotations

from datetime import timedelta, timezone

import pandas as pd
from sqlalchemy import select
from sqlalchemy.orm import Session as DbSession

from app.core.logging import get_logger
from app.models.catalog import Album, Artist, Genre, Song
from app.models.user import User, utcnow
from app.services import event_service, session_service

logger = get_logger(__name__)

DEMO_USER_ID = "usr_demo"
VALID_EVENTS = {"play", "like", "save", "skip", "dislike"}


def _slug(value: str) -> str:
    return value.strip().lower().replace(" ", "-").replace("&", "and")


def _opt_float(value) -> float | None:
    if value is None:
        return None
    try:
        f = float(value)
    except (TypeError, ValueError):
        return None
    return None if pd.isna(f) else f


def _opt_int(value) -> int | None:
    f = _opt_float(value)
    return None if f is None else int(f)


def _opt_str(value) -> str | None:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return None
    s = str(value).strip()
    return s or None


def _as_list(value) -> list:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return []
    if isinstance(value, (list, tuple)):
        return list(value)
    if isinstance(value, str):
        return [p for p in value.split("|") if p]
    return []


def load_catalog_frames() -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame | None]:
    """Prefer data/sample CSVs; fall back to data/processed parquet."""
    from ml.utils.paths import PROCESSED_DATA_DIR, SAMPLE_DATA_DIR

    sample_songs = SAMPLE_DATA_DIR / "songs.csv"
    if sample_songs.exists():
        songs = pd.read_csv(sample_songs)
        artists = pd.read_csv(SAMPLE_DATA_DIR / "artists.csv")
        interactions_path = SAMPLE_DATA_DIR / "interactions.csv"
        interactions = (
            pd.read_csv(interactions_path, parse_dates=["timestamp"])
            if interactions_path.exists() else None
        )
        return songs, artists, interactions

    from ml.preprocessing.pipeline import load_processed

    tables = load_processed(PROCESSED_DATA_DIR)
    return tables["songs"], tables["artists"], tables["interactions"]


def seed_database(db: DbSession, with_demo_history: bool = True, history_limit: int = 1500) -> dict:
    existing = db.execute(select(Song).limit(1)).first()
    if existing is not None:
        logger.info("Database already contains catalog data; skipping seed")
        return {"status": "skipped"}

    songs_df, artists_df, interactions_df = load_catalog_frames()
    logger.info("Seeding %d artists, %d songs", len(artists_df), len(songs_df))

    genre_cache: dict[str, Genre] = {}

    def get_genre(name: str) -> Genre:
        slug = _slug(str(name))
        if slug not in genre_cache:
            genre = db.execute(select(Genre).where(Genre.id == slug)).scalar_one_or_none()
            if genre is None:
                genre = Genre(id=slug, name=str(name).strip().lower())
                db.add(genre)
                db.flush()
            genre_cache[slug] = genre
        return genre_cache[slug]

    for row in artists_df.itertuples(index=False):
        db.add(Artist(
            id=str(row.artist_id),
            name=str(row.name),
            genres=[str(g) for g in _as_list(getattr(row, "genres", []))],
            followers=_opt_float(getattr(row, "followers", 0.0)) or 0.0,
        ))
    db.flush()

    album_cache: dict[str, Album] = {}
    for row in songs_df.itertuples(index=False):
        album_title = _opt_str(getattr(row, "album", None))
        album_id = None
        if album_title:
            album_id = f"al_{_slug(str(row.artist_id))}_{_slug(album_title)}"[:64]
            if album_id not in album_cache:
                db.add(Album(id=album_id, title=album_title, artist_id=str(row.artist_id),
                             release_year=_opt_int(getattr(row, "release_year", None))))
                album_cache[album_id] = Album(id=album_id, title=album_title, artist_id=str(row.artist_id))

        song = Song(
            id=str(row.song_id),
            title=str(row.title),
            artist_id=str(row.artist_id),
            album_id=album_id,
            release_year=_opt_int(getattr(row, "release_year", None)),
            duration_ms=_opt_float(getattr(row, "duration_ms", None)),
            tags=[str(t) for t in _as_list(getattr(row, "tags", []))],
            preview_url=_opt_str(getattr(row, "preview_url", None)),
            artwork_url=_opt_str(getattr(row, "artwork_url", None)),
            energy=_opt_float(getattr(row, "energy", None)),
            danceability=_opt_float(getattr(row, "danceability", None)),
            valence=_opt_float(getattr(row, "valence", None)),
            acousticness=_opt_float(getattr(row, "acousticness", None)),
            instrumentalness=_opt_float(getattr(row, "instrumentalness", None)),
            speechiness=_opt_float(getattr(row, "speechiness", None)),
            loudness=_opt_float(getattr(row, "loudness", None)),
            tempo=_opt_float(getattr(row, "tempo", None)),
            popularity=_opt_float(getattr(row, "popularity", None)),
        )
        song.genres = [get_genre(g) for g in _as_list(getattr(row, "genres", []))]
        db.add(song)
    db.flush()

    demo = User(id=DEMO_USER_ID, display_name="Demo Listener",
                preferred_genres=["electronic", "indie"], created_at=utcnow())
    db.add(demo)
    db.flush()

    seeded_events = 0
    if with_demo_history and interactions_df is not None and len(interactions_df):
        seeded_events = _seed_demo_history(db, DEMO_USER_ID, interactions_df, history_limit)

    db.commit()
    logger.info("Seed complete: %d artists, %d songs, %d genres, %d demo events",
                len(artists_df), len(songs_df), len(genre_cache), seeded_events)
    return {"status": "seeded", "songs": len(songs_df), "artists": len(artists_df),
            "demo_events": seeded_events}


def _seed_demo_history(db: DbSession, user_id: str, interactions: pd.DataFrame, limit: int) -> int:
    """Replay a slice of the sample interactions for the demo user."""
    if "timestamp" in interactions.columns and interactions["timestamp"].notna().any():
        interactions = interactions.sort_values("timestamp")
    source_users = sorted(interactions["user_id"].unique())[:2]
    subset = interactions[interactions["user_id"].isin(source_users)].tail(limit)

    # compress the historical window so the demo session looks recent
    now = utcnow()
    timestamps = pd.to_datetime(subset.get("timestamp"), errors="coerce")
    if timestamps.notna().any():
        span_days = max((timestamps.max() - timestamps.min()).days, 1)
        window = timedelta(days=min(span_days, 14))
        start = now - window

    session_map: dict[str, str] = {}
    count = 0
    for i, row in enumerate(subset.itertuples(index=False)):
        if row.event_type not in VALID_EVENTS:
            continue
        raw_session = getattr(row, "session_id", None) or f"seed_{i // 8}"
        if raw_session not in session_map:
            session = session_service.create_session(db, user_id)
            session_map[raw_session] = session.id

        ts = getattr(row, "timestamp", None)
        if isinstance(ts, pd.Timestamp) and not pd.isna(ts):
            fraction = (ts - timestamps.min()).total_seconds() / max(
                (timestamps.max() - timestamps.min()).total_seconds(), 1.0)
            event_time = start + fraction * (now - start)
        else:
            event_time = now - timedelta(minutes=(len(subset) - i) * 5)
        event_time = event_time.replace(tzinfo=timezone.utc) if event_time.tzinfo is None else event_time

        try:
            event_service.record_event(
                db, user_id, str(row.song_id), str(row.event_type),
                session_id=session_map[raw_session], timestamp=event_time)
            count += 1
        except event_service.EventServiceError:
            continue
    return count
